    fun translate(context: Context, value: String): String {
        val localized = LocaleHelper.wrap(context)
        messages[value]?.let { return localized.getString(it) }
        if (localized.resources.configuration.locales[0].language != "kk") return value
        val patterns = listOf(
            "(.*) Разговор продолжается; оценка неполная\\." to "%s Сөйлесу жалғасуда; бағалау толық емес.",
            "(.*)\\. Запись сохранена на телефоне\\." to "%s. Жазба телефонда сақталды.",
            "(.*)\\. Передача остановлена; запись на телефоне продолжается\\." to "%s. Жіберу тоқтатылды; телефонда жазу жалғасуда.",
            "Ошибка записи\\. (.*)" to "Жазу қатесі. %s",
            "Ошибка сервера: (.*)" to "Сервер қатесі: %s",
            "Ошибка соединения(.*)\\. Проверьте адрес сервера и сеть" to "Қосылым қатесі%s. Сервер мекенжайы мен желіні тексеріңіз",
            "Сервер закрыл соединение до завершения обработки \\(код (.*)\\)" to "Сервер өңдеу аяқталмай тұрып қосылымды жапты (код %s)",
            "Не удалось получить звук с микрофона \\(код (.*)\\)" to "Микрофоннан дыбыс алу мүмкін болмады (код %s)"
        )
        for ((pattern, format) in patterns) {
            Regex(pattern, RegexOption.DOT_MATCHES_ALL).matchEntire(value)?.let {
                return format.format(translate(context, it.groupValues[1]))
            }
        }
        return when (value) {
            "Анализ доступен принимающему участнику" -> localized.getString(R.string.scene_caller_desc)
            "Сигнальный канал недоступен" -> "Сигнал алмасу арнасы қолжетімсіз"
            else -> value
        }
    }
